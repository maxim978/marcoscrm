// Deterministic daily spend per day index (0=weekday, pattern repeats)
const DAY_SPEND = [
  52, 48, 61, 55, 58, 98, 112, // week 1
  50, 47, 63, 57, 60, 102, 108, // week 2
  54, 49, 65, 59, 62, 105, 115, // week 3
  56, 51, 67, 61, 64, 108, 118, // week 4 + 2
  58, 53,
]

export function generateDailyMetrics(days = 30): DailyMetric[] {
  const metrics: DailyMetric[] = []
  const base = new Date('2026-07-03')

  for (let i = 0; i < days; i++) {
    const date = new Date(base)
    date.setDate(base.getDate() + i)
    const dateStr = date.toISOString().split('T')[0]
    const spend = DAY_SPEND[i] ?? 55
    const impressions = Math.round(spend * 1200 + (i * 50))
    const reach = Math.round(impressions * 0.82)
    const videoViews = Math.round(impressions * 0.7)
    const clicks = Math.round(impressions * (0.012 + (i % 7 === 5 || i % 7 === 6 ? 0.008 : 0)))
    const ctr = (clicks / impressions) * 100
    const cpm = (spend / impressions) * 1000
    const cpc = clicks > 0 ? spend / clicks : 0
    const profileVisits = Math.round(clicks * 0.35)
    const followers = Math.round(5 + (i % 7 === 5 || i % 7 === 6 ? 18 : 8) + (i * 0.3))
    const likes = Math.round(videoViews * 0.06)
    const comments = Math.round(videoViews * 0.008)
    const shares = Math.round(videoViews * 0.015)

    metrics.push({
      date: dateStr,
      spend,
      impressions,
      reach,
      videoViews,
      clicks,
      ctr,
      cpm,
      cpc,
      profileVisits,
      followers,
      likes,
      comments,
      shares,
    })
  }
  return metrics
}

